const LANGS = {uz: "🇺🇿 O'zbek", ru: "🇷🇺 Русский", en: "🇬🇧 English"};
let LANG = (() => {
  try { const s = localStorage.getItem('bilimdon_lang'); if (s && I18N[JSON.parse(s)]) return JSON.parse(s); } catch (e) {}
  const nav = (navigator.language || '').slice(0, 2);
  return nav === 'ru' ? 'ru' : nav === 'en' ? 'en' : 'uz';
})();
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.uz[key] ?? key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-t]').forEach(el => el.textContent = t(el.dataset.t));
  document.querySelectorAll('[data-tph]').forEach(el => el.placeholder = t(el.dataset.tph));
  document.querySelectorAll('[data-ttitle]').forEach(el => el.title = t(el.dataset.ttitle));
  const play = document.getElementById('play');
  if (play) play.dataset.pause = t('pauseOverlay');  // shown by CSS while the host pauses
}
